// Copies the API contracts in shared/src (Zod schemas, DTO types, labels, helpers) into the
// frontend repository, which keeps an identical copy under shared/. This repository is the
// source of truth: change the contracts here, run the tests, then export and commit both sides.
//   npm run shared:export -- ../jigar-pot-shop            # copy
//   npm run shared:export -- ../jigar-pot-shop --check    # exit 1 if the copies differ
import { createHash } from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const source = path.join(root, 'shared/src');
const [target, flag] = process.argv.slice(2);
if (!target) {
  console.error('Usage: npm run shared:export -- <frontend-repo-path> [--check]');
  process.exit(1);
}
const destination = path.join(path.resolve(target), 'shared/src');

async function list(dir, base = dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true }).catch(() => []);
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await list(full, base)));
    else files.push(path.relative(base, full));
  }
  return files.sort();
}

async function digest(dir) {
  const hash = createHash('sha256');
  for (const file of await list(dir)) {
    hash.update(file);
    hash.update(await fs.readFile(path.join(dir, file)));
  }
  return hash.digest('hex').slice(0, 16);
}

const [from, to] = [await digest(source), await digest(destination)];
if (flag === '--check') {
  console.log(from === to ? `shared/ in sync (${from})` : `shared/ differs: ${from} ≠ ${to}`);
  process.exit(from === to ? 0 : 1);
}
await fs.rm(destination, { recursive: true, force: true });
await fs.cp(source, destination, { recursive: true });
await fs.writeFile(
  path.join(path.dirname(destination), 'VERSION'),
  `${from}\n# Generated by jigar-pot-shop-backend: npm run shared:export. Do not edit shared/src here.\n`,
);
console.log(`Exported shared/src (${from}) to ${destination}`);
